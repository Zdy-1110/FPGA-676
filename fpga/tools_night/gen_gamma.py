#!/usr/bin/env python3
"""
gen_gamma.py
Generate gamma=0.5 lookup table:
    out = round(255 * (in / 255) ** 0.5), for in = 0..255
Outputs:
  1) gamma_lut.txt : 256 lines of decimal integers (0..255)
  2) gamma_lut.vh  : Verilog function definition for rt_night.v
"""

import os
import sys

def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    proj_dir = os.path.dirname(script_dir)
    sim_dir = os.path.join(proj_dir, "sim_night")
    src_disp_dir = os.path.join(proj_dir, "src", "disp")

    lut = [round(255.0 * (i / 255.0) ** 0.5) for i in range(256)]

    # Validate key values
    assert len(lut) == 256
    assert lut[0] == 0, f"Expected lut[0]==0, got {lut[0]}"
    assert lut[64] == 128, f"Expected lut[64]==128, got {lut[64]}"
    assert lut[255] == 255, f"Expected lut[255]==255, got {lut[255]}"

    # Text content for gamma_lut.txt
    txt_content = "\n".join(str(val) for val in lut) + "\n"

    # Verilog function content for gamma_lut.vh
    vh_lines = [
        "// Generated by tools_night/gen_gamma.py - DO NOT EDIT MANUALLY",
        "function [7:0] gamma_lut;",
        "    input [7:0] in_val;",
        "    begin",
        "        case (in_val)"
    ]
    for i, val in enumerate(lut):
        vh_lines.append(f"            8'd{i:3d}: gamma_lut = 8'd{val:3d};")
    vh_lines.append("            default: gamma_lut = in_val;")
    vh_lines.append("        endcase")
    vh_lines.append("    end")
    vh_lines.append("endfunction")
    vh_content = "\n".join(vh_lines) + "\n"

    # Targets for gamma_lut.txt
    targets_txt = [
        os.path.join(script_dir, "gamma_lut.txt"),
        os.path.join(sim_dir, "gamma_lut.txt"),
        "gamma_lut.txt"
    ]
    for p in targets_txt:
        try:
            d = os.path.dirname(p)
            if d and not os.path.exists(d):
                os.makedirs(d, exist_ok=True)
            with open(p, "w", encoding="utf-8") as f:
                f.write(txt_content)
        except Exception as e:
            print(f"Notice: failed writing to {p}: {e}")

    # Targets for gamma_lut.vh
    targets_vh = [
        os.path.join(script_dir, "gamma_lut.vh"),
        os.path.join(src_disp_dir, "gamma_lut.vh"),
        os.path.join(sim_dir, "gamma_lut.vh")
    ]
    for p in targets_vh:
        try:
            d = os.path.dirname(p)
            if d and not os.path.exists(d):
                os.makedirs(d, exist_ok=True)
            with open(p, "w", encoding="utf-8") as f:
                f.write(vh_content)
        except Exception as e:
            print(f"Notice: failed writing to {p}: {e}")

    print("Successfully generated gamma LUT:")
    print(f"  lut[0]   = {lut[0]}")
    print(f"  lut[64]  = {lut[64]}")
    print(f"  lut[255] = {lut[255]}")
    print(f"  total lines = {len(lut)}")

if __name__ == "__main__":
    main()
